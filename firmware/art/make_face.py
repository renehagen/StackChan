"""Bake the curved StackChan artwork at 6x resolution, then downsample to LCD pixels.
Run with Pillow to regenerate face.rgb565 and FaceTiles.h after editing the artwork.
"""
from pathlib import Path
from struct import pack
from PIL import Image, ImageDraw

HERE = Path(__file__).resolve().parent
S = 6
BG = "#0d1825"
MINT = "#78fab2"
GLINT = "#faf9f2"
PEACH = "#ffb48c"
blob = bytearray()
tiles = []


def tile(name, w, h, paint):
    im = Image.new("RGB", (w * S, h * S), BG)
    paint(ImageDraw.Draw(im))
    tiles.append((name, len(blob), w, h))
    for r, g, b in im.resize((w, h), Image.Resampling.LANCZOS).getdata():
        blob.extend(pack(">H", ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)))


def oval(d, x, y, rx, ry, color):
    d.ellipse(tuple(round(v * S) for v in (x-rx, y-ry, x+rx, y+ry)), fill=color)


def bezier(p0, p1, p2, p3):
    points = []
    for i in range(65):
        t = i / 64
        u = 1 - t
        points.append(tuple(round(S * (u**3*a + 3*u*u*t*b + 3*u*t*t*c + t**3*d))
                            for a, b, c, d in zip(p0, p1, p2, p3)))
    return points


def stroke(d, width, color, *points):
    d.line(bezier(*points), fill=color, width=round(width*S), joint="curve")
    for x, y in (points[0], points[-1]):
        oval(d, x, y, width/2, width/2, color)


def eye(d, opening):
    if opening == 0:
        stroke(d, 5, MINT, (6, 36), (18, 29), (39, 29), (50, 36))
        return
    # A continuous, slightly tapered oval like the eyes in the approved mockup.
    def outline(top, bottom, left, right):
        cx, cy = 28, 34
        def pt(x,y):
            return (x, cy + (y-cy)*opening)
        return (bezier(pt(cx,top), pt(right+2,top), pt(right,cy-5), pt(right,cy))
                + bezier(pt(right,cy), pt(right,cy+18), pt(right-2,bottom), pt(cx,bottom))
                + bezier(pt(cx,bottom), pt(left+1,bottom), pt(left,cy+16), pt(left,cy))
                + bezier(pt(left,cy), pt(left,cy-16), pt(left-1,top), pt(cx,top)))
    d.polygon(outline(2,67,2,54), fill=MINT)
    d.polygon(outline(9,60,9,47), fill=BG)
    oval(d, 35, 34-16*opening, 4.9, 4.9*opening, GLINT)
    oval(d, 41, 34-5*opening, 2.3, 2.3*opening, GLINT)


def cheeks(d):
    stroke(d, 3.4, PEACH, (4,10), (6,9), (9,6), (11,4))
    stroke(d, 3.4, PEACH, (15,10), (17,8), (20,6), (22,3))


def mouth(d, step):
    top = bezier((6,9), (17,16-step*1.6), (38,16-step*1.6), (49,9))
    bottom = bezier((49,9), (40,23+step*2.1), (15,23+step*2.1), (6,9))
    d.polygon(top + bottom, fill=MINT)
    if step >= 2:
        oval(d, 27.5, 16 + step*0.08, 3+step, .8+step*.64, BG)


tile("LeftBrow", 61, 30, lambda d: stroke(d, 6, MINT, (5,25),(18,11),(37,3),(55,7)))
tile("RightBrow", 56, 24, lambda d: stroke(d, 5.5, MINT, (5,6),(22,4),(39,10),(51,18)))
tile("Cheek", 27, 15, cheeks)
for n, opening in enumerate((1, .52, 0)):
    tile(f"Eye{n}", 57, 70, lambda d: eye(d, opening))
for n in range(6):
    tile(f"Mouth{n}", 56, 34, lambda d: mouth(d, n))

(HERE / "face.rgb565").write_bytes(blob)
header = ["// Generated by art/make_face.py. Offsets are in bytes, RGB565 is big-endian.",
          "#pragma once", "#include <cstdint>", "namespace face {",
          "struct Tile { unsigned offset; int w, h; };"]
for name, offset, w, h in tiles:
    header.append(f"constexpr Tile k{name}{{{offset}, {w}, {h}}};")
header += ["constexpr Tile eyes[] = {kEye0, kEye1, kEye2};",
           "constexpr Tile mouths[] = {kMouth0, kMouth1, kMouth2, kMouth3, kMouth4, kMouth5};",
           "}  // namespace face"]
(HERE.parent / "src/FaceTiles.h").write_text("\n".join(header)+"\n")
